function buildSuggestions(): QuickSuggestion[] {
  let nextId = 1
  return suggestionGroups.flatMap((group) =>
    group.titles.map((title) => ({
      id: `quick-${String(nextId++).padStart(3, "0")}`,
      icon: group.icon,
      title,
      prompt: group.prefix.replace("${title}", title),
    }))
  )
}

export const quickSuggestions = buildSuggestions()

export function pickQuickSuggestions(count = 4): QuickSuggestion[] {
  const pool = [...quickSuggestions]
  for (let index = pool.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1))
    ;[pool[index], pool[swapIndex]] = [pool[swapIndex], pool[index]]
  }
  return pool.slice(0, Math.min(Math.max(count, 0), pool.length))
}
